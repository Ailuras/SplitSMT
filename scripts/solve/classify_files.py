#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
SMT Files Classification Script
This script reads an Excel analysis file and classifies SMT files based on their solving results.

Usage:
    python classify_files.py --excel-file <excel_file> --output-dir <output_dir> [--source-dir <source_dir>]

Example:
    python scripts/solve/classify_files.py --excel-file charts/results_test_ext_cvc5_analysis.xlsx --output-dir classified_results --source-dir benchmarks/test

Features:
- Reads Excel analysis files generated by simple_analysis.py
- Creates subdirectories for each result type (SAT, UNSAT, UNKNOWN, UNCLEAR, ERROR, TIMEOUT)
- Copies SMT files to appropriate subdirectories based on solving results
- Provides detailed statistics about the classification
- Handles missing files gracefully
"""

import os
import shutil
import pandas as pd
import argparse
from pathlib import Path
from tqdm import tqdm

def parse_args():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(description='Classify SMT files based on solving results from Excel analysis.')
    parser.add_argument('--excel-file', required=True, help='Excel analysis file containing solving results')
    parser.add_argument('--output-dir', required=True, help='Output directory to create classified subdirectories')
    parser.add_argument('--source-dir', help='Source directory containing SMT files (if different from paths in Excel)')
    parser.add_argument('--dry-run', action='store_true', help='Show what would be done without actually copying files')
    
    return parser.parse_args()

def create_result_directories(output_dir, clean=True):
    """Create subdirectories for each result type."""
    result_types = ['SAT', 'UNSAT', 'UNKNOWN', 'UNCLEAR', 'ERROR', 'WARN', 'TIMEOUT']
    created_dirs = {}
    
    # Clean existing directories if requested
    if clean and os.path.exists(output_dir):
        print(f"Cleaning existing directory: {output_dir}")
        shutil.rmtree(output_dir)
    
    # Create output directory
    os.makedirs(output_dir, exist_ok=True)
    
    for result_type in result_types:
        dir_path = os.path.join(output_dir, result_type.lower())
        os.makedirs(dir_path, exist_ok=True)
        created_dirs[result_type] = dir_path
        print(f"Created directory: {dir_path}")
    
    return created_dirs

def read_excel_analysis(excel_file):
    """Read the Excel analysis file and extract file information."""
    try:
        # Try to read the first sheet (usually the results sheet)
        df = pd.read_excel(excel_file, sheet_name=0)
        print(f"Successfully read Excel file: {excel_file}")
        print(f"Found {len(df)} files in analysis")
        
        # Display column names for debugging
        print(f"Columns in Excel: {list(df.columns)}")
        
        return df
    
    except Exception as e:
        print(f"Error reading Excel file {excel_file}: {e}")
        return None

def determine_result_category(row):
    """Determine the result category for a file based on its analysis data."""
    # Check result column first
    if 'result' in row and pd.notna(row['result']):
        result = str(row['result']).strip().upper()
        if result == 'ERROR':
            return 'ERROR'
        elif result == 'TIMEOUT':
            return 'TIMEOUT'
    
    # Check sat_result column
    if 'sat_result' in row and pd.notna(row['sat_result']):
        sat_result = str(row['sat_result']).strip().upper()
        # All warning types (SAT_WARN, UNSAT_WARN, WARN) should go to WARN folder
        if 'WARN' in sat_result:
            return 'WARN'
        elif sat_result == 'SAT':
            return 'SAT'
        elif sat_result == 'UNSAT':
            return 'UNSAT'
        elif sat_result == 'UNKNOWN':
            return 'UNKNOWN'
        elif sat_result == 'UNCLEAR':
            return 'UNCLEAR'
        elif sat_result == 'ERROR':
            return 'ERROR'
    
    # Default category for unclassified files (previously OTHER)
    return 'UNCLEAR'

def find_source_file(file_name, file_path, source_dir):
    """Find the source SMT file, trying different locations."""
    # Priority order for finding files:
    # 1. Use the path from Excel if it exists
    # 2. Look in source_dir if provided
    # 3. Look in current directory and subdirectories
    
    candidates = []
    
    # Try the path from Excel first
    if file_path and pd.notna(file_path) and os.path.exists(str(file_path)):
        candidates.append(str(file_path))
    
    # Try source_dir if provided
    if source_dir:
        source_path = os.path.join(source_dir, file_name)
        if os.path.exists(source_path):
            candidates.append(source_path)
        
        # Also try to find recursively in source_dir
        for root, dirs, files in os.walk(source_dir):
            if file_name in files:
                candidates.append(os.path.join(root, file_name))
    
    # Try current directory and subdirectories
    for root, dirs, files in os.walk('.'):
        if file_name in files:
            candidates.append(os.path.join(root, file_name))
    
    # Return the first existing file
    for candidate in candidates:
        if os.path.exists(candidate):
            return candidate
    
    return None

def classify_files(df, result_dirs, source_dir, dry_run=False):
    """Classify and copy files based on their solving results."""
    stats = {category: 0 for category in result_dirs.keys()}
    missing_files = []
    
    print(f"\nClassifying {len(df)} files...")
    
    # Create progress bar
    pbar = tqdm(df.iterrows(), total=len(df), desc="Classifying files", unit="file")
    
    for index, row in pbar:
        # Get file information
        file_name = str(row.get('file_name', '')).strip()
        file_path = row.get('path', '')
        
        if not file_name:
            pbar.write(f"Warning: Empty file name at row {index}")
            continue
        
        # Determine result category
        category = determine_result_category(row)
        
        # Find source file
        source_file = find_source_file(file_name, file_path, source_dir)
        
        if source_file is None:
            missing_files.append(file_name)
            pbar.write(f"Warning: Could not find source file: {file_name}")
            continue
        
        # Determine destination
        dest_dir = result_dirs[category]
        dest_file = os.path.join(dest_dir, file_name)
        
        # Copy file (or show what would be done in dry run)
        if dry_run:
            pbar.write(f"Would copy: {source_file} -> {dest_file} ({category})")
        else:
            try:
                shutil.copy2(source_file, dest_file)
            except Exception as e:
                pbar.write(f"Error copying {source_file} to {dest_file}: {e}")
                missing_files.append(file_name)
                continue
        
        stats[category] += 1
        
        # Update progress bar description with current stats
        pbar.set_postfix({
            'SAT': stats['SAT'],
            'UNSAT': stats['UNSAT'], 
            'UNKNOWN': stats['UNKNOWN'],
            'ERROR': stats['ERROR'],
            'WARN': stats['WARN']
        })
    
    pbar.close()
    return stats, missing_files

def print_classification_summary(stats, missing_files, total_files):
    """Print a summary of the classification results."""
    print("\n" + "="*60)
    print("CLASSIFICATION SUMMARY")
    print("="*60)
    
    print(f"Total files processed: {total_files}")
    print(f"Successfully classified: {sum(stats.values())}")
    print(f"Missing files: {len(missing_files)}")
    
    print("\nFiles by category:")
    for category, count in stats.items():
        if count > 0:
            percentage = (count / total_files) * 100 if total_files > 0 else 0
            print(f"  {category:8}: {count:4} files ({percentage:5.1f}%)")
    
    if missing_files:
        print(f"\nMissing files ({len(missing_files)}):")
        for i, file_name in enumerate(missing_files[:10]):  # Show first 10
            print(f"  - {file_name}")
        if len(missing_files) > 10:
            print(f"  ... and {len(missing_files) - 10} more")
    
    print("="*60)

def main():
    args = parse_args()
    
    # Validate inputs
    if not os.path.exists(args.excel_file):
        print(f"Error: Excel file not found: {args.excel_file}")
        return 1
    
    if args.source_dir and not os.path.exists(args.source_dir):
        print(f"Error: Source directory not found: {args.source_dir}")
        return 1
    
    print(f"Reading Excel analysis file: {args.excel_file}")
    df = read_excel_analysis(args.excel_file)
    
    if df is None or df.empty:
        print("Error: Could not read Excel file or file is empty")
        return 1
    
    if args.dry_run:
        print("\n*** DRY RUN MODE - No files will be copied ***")
    
    print(f"Creating output directory: {args.output_dir}")
    os.makedirs(args.output_dir, exist_ok=True)
    
    print("Creating result subdirectories...")
    result_dirs = create_result_directories(args.output_dir, clean=True)
    
    print(f"Classifying files...")
    if args.source_dir:
        print(f"Using source directory: {args.source_dir}")
    else:
        print("Using file paths from Excel analysis")
    
    stats, missing_files = classify_files(df, result_dirs, args.source_dir, args.dry_run)
    
    print_classification_summary(stats, missing_files, len(df))
    
    if not args.dry_run:
        print(f"\nClassification complete! Files organized in: {args.output_dir}")
    
    return 0

if __name__ == "__main__":
    exit(main()) 