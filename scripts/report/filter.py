#!/usr/bin/env python3
"""Filter SMT examples based on aggregate Excel report.

This script reads the aggregate.xlsx generated by scripts/report/aggregate.py,
identifies files that are classified as 'Hard' or 'Error' (or custom filters),
and deletes them from the filesystem.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from dataclasses import dataclass
from typing import Dict, List, Optional
from openpyxl import load_workbook

@dataclass
class TargetedFile:
    source: Path
    consistency: str
    filename: str

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Delete SMT files based on aggregate.xlsx consistency labels (e.g. Error, Hard)."
    )
    parser.add_argument(
        "xlsx_file",
        type=Path,
        help="Excel file produced by scripts/report/aggregate.py",
    )
    parser.add_argument(
        "--targets",
        nargs="+",
        default=["Error", "Hard"],
        help="Consistency labels to target for deletion (default: Error Hard).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Only show what would be deleted, do not actually delete.",
    )
    return parser.parse_args()

def collect_targets(
    xlsx_file: Path,
    target_labels: List[str],
) -> List[TargetedFile]:
    workbook = load_workbook(xlsx_file, read_only=True, data_only=True)
    try:
        if "Results" not in workbook.sheetnames:
            print(f"error: 'Results' sheet not found in {xlsx_file}", file=sys.stderr)
            sys.exit(1)
        worksheet = workbook["Results"]

        headers = {
            str(cell.value).strip(): idx
            for idx, cell in enumerate(worksheet[1], start=1)
            if cell.value
        }
        path_col = headers.get("path")
        filename_col = headers.get("filename")
        consistency_col = headers.get("consistency")

        if path_col is None or filename_col is None or consistency_col is None:
            print("error: 'path', 'filename', or 'consistency' column not found", file=sys.stderr)
            sys.exit(1)

        targets: List[TargetedFile] = []
        normalized_targets = {t.upper().strip() for t in target_labels}

        for row in worksheet.iter_rows(min_row=2):
            path_cell = row[path_col - 1].value
            filename_cell = row[filename_col - 1].value
            consistency_cell = row[consistency_col - 1].value

            if not path_cell:
                continue

            consistency_val = str(consistency_cell).strip() if consistency_cell else "Other"
            
            if consistency_val.upper() in normalized_targets:
                path_str = str(path_cell).strip()
                filename_str = str(filename_cell).strip() if filename_cell else ""
                
                source_path = Path(path_str).expanduser()
                
                targets.append(TargetedFile(
                    source=source_path,
                    consistency=consistency_val,
                    filename=filename_str
                ))

        return targets
    finally:
        workbook.close()

def delete_files(files: List[TargetedFile], dry_run: bool = False) -> None:
    deleted = 0
    missing = 0
    failed = 0
    
    print(f"Found {len(files)} files matching targets.")
    
    for entry in sorted(files, key=lambda x: str(x.source)):
        path = entry.source
        
        if not path.exists():
            print(f"[MISSING] {path}")
            missing += 1
            continue
            
        if dry_run:
            print(f"[WOULD DELETE] {path} ({entry.consistency})")
            deleted += 1
        else:
            try:
                path.unlink()
                print(f"[DELETED] {path} ({entry.consistency})")
                deleted += 1
            except Exception as e:
                print(f"[FAILED] {path}: {e}")
                failed += 1
                
    print("-" * 60)
    print("Summary:")
    if dry_run:
        print(f"  Would delete: {deleted}")
    else:
        print(f"  Deleted: {deleted}")
    print(f"  Missing: {missing}")
    print(f"  Failed:  {failed}")
    print("-" * 60)

def main():
    args = parse_args()
    
    if not args.xlsx_file.exists():
        print(f"error: Excel file not found: {args.xlsx_file}", file=sys.stderr)
        return 1
        
    print(f"Scanning {args.xlsx_file} for targets: {', '.join(args.targets)}")
    
    targets = collect_targets(args.xlsx_file, args.targets)
    
    if not targets:
        print("No matching files found.")
        return 0
        
    delete_files(targets, args.dry_run)
    return 0

if __name__ == "__main__":
    sys.exit(main())
